from django.contrib import admin
from django.contrib.auth import views as auth_views
from django.urls import include, path

urlpatterns = [
    path('admin/', admin.site.urls),
    path('accounts/', include('django.contrib.auth.urls')),
    
    # Core App Routes (Login, Dashboard, Portals)
    path('', include('core.urls')),

    # 1. Password Reset Request Form (User enters email)
    path(
        'password-reset/',
        auth_views.PasswordResetView.as_view(
            template_name='accounts/password_reset.html',
            email_template_name='accounts/password_reset_email.txt',        # Plain text fallback
            html_email_template_name='accounts/password_reset_email.html',  # Styled HTML version with button
            subject_template_name='accounts/password_reset_subject.txt',
        ),
        name='password_reset',
    ),

    # 2. Password Reset Done Notice (Confirmation email sent message)
    path(
        'password-reset/done/',
        auth_views.PasswordResetDoneView.as_view(
            template_name='accounts/password_reset_done.html'
        ),
        name='password_reset_done',
    ),

    # 3. Password Reset Confirm Form (User enters new password via token link)
    path(
        'reset/<uidb64>/<token>/',
        auth_views.PasswordResetConfirmView.as_view(
            template_name='registration/password_reset_confirm.html'
        ),
        name='password_reset_confirm',
    ),

    # 4. Password Reset Complete (Success notice after password is changed)
    path(
        'reset/done/',
        auth_views.PasswordResetCompleteView.as_view(
            template_name='registration/password_reset_complete.html'
        ),
        name='password_reset_complete',
    ),
]